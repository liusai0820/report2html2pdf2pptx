# So What 原则
# ============================================================
SO_WHAT_PRINCIPLE = """
## So What 原则

每一页都要回答：所以呢？这意味着什么？

### 层层追问
1. 数据/事实 → So What?
2. 发现/洞察 → So What?
3. 结论/建议 → 行动

### 应用示例
- 数据：销售额下降 15%
- So What? → 主要是华东区下降，其他区域稳定
- So What? → 华东区新竞品上市抢占了份额
- So What? → 需要针对华东区制定反击策略
- 行动：建议在华东区推出促销活动 + 新品上市

### PPT 应用
- 不要只展示数据，要解读数据
- 不要只描述现象，要分析原因
- 不要只提出问题，要给出建议
"""

# ============================================================
# 一页一观点原则
# ============================================================
ONE_MESSAGE_PER_SLIDE = """
## 一页一观点原则

每页 PPT 只传达一个核心信息。

### 为什么重要
1. 观众注意力有限，信息过多会稀释重点
2. 便于记忆和传播
3. 便于讨论和决策

### 如何判断
- 能否用一句话概括这页的核心信息？
- 这页的所有内容是否都在支撑同一个观点？
- 删掉任何一部分，核心信息是否受影响？

### 常见错误
- 一页塞入多个不相关的数据
- 一页讨论多个话题
- 一页既有问题又有解决方案（应该分开）
"""

# ============================================================
# 数据可视化原则
# ============================================================
DATA_VISUALIZATION_PRINCIPLE = """
## 数据可视化原则

数据不是用来展示的，是用来说服的。

### 选择图表类型
- **比较**：柱状图、条形图
- **趋势**：折线图、面积图
- **占比**：饼图、环形图（不超过 5 个类别）
- **分布**：散点图、直方图
- **关系**：气泡图、热力图

### 数据呈现原则
1. **突出重点**：用颜色、大小突出关键数据
2. **简化信息**：删除不必要的网格线、边框
3. **添加标注**：关键数据点直接标注数值
4. **提供对比**：同比、环比、目标对比

### 数据解读
- 不要让观众自己找结论
- 用文字明确指出数据说明了什么
- 数据要服务于你的论点
"""

