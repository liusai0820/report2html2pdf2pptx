# 方法论集合
# ============================================================
METHODOLOGIES = {
    "pyramid": PYRAMID_PRINCIPLE,
    "scq": SCQ_FRAMEWORK,
    "scqa": SCQA_FRAMEWORK,
    "action_title": ACTION_TITLE_PRINCIPLE,
    "so_what": SO_WHAT_PRINCIPLE,
    "one_message": ONE_MESSAGE_PER_SLIDE,
    "data_viz": DATA_VISUALIZATION_PRINCIPLE,
    "structures": REPORT_STRUCTURES,
}


def get_methodology_prompt(methodology_ids: list) -> str:
    """获取指定方法论的组合 Prompt"""
    parts = []
    for mid in methodology_ids:
        if mid in METHODOLOGIES:
            content = METHODOLOGIES[mid]
            if isinstance(content, dict):
                parts.append(str(content))
            else:
                parts.append(content)
    return "\n\n".join(parts)
