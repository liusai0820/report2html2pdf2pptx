ACTION_TITLE_PRINCIPLE = """
## 行动标题原则

标题不是主题描述，而是核心结论。

### 错误示例 ❌
- "市场分析"
- "竞争对手情况"
- "财务数据"
- "下一步计划"

### 正确示例 ✅
- "市场规模 5 年内将翻倍，我们必须加速布局"
- "三大竞争对手均在加码研发，我们面临技术落后风险"
- "营收增长 45%，但利润率下滑 3 个百分点需要关注"
- "建议分三阶段推进，首期聚焦核心城市"

### 检验标准
- 读完标题，就知道这页要说什么
- 标题本身就是一个完整的观点
- 标题能独立成为汇报的摘要
"""

