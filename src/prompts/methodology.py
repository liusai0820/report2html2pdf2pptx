# SCQA 完整框架
# ============================================================
SCQA_FRAMEWORK = """
## SCQA 框架

在 SCQ 基础上增加 Answer，形成完整的说服结构。

### 四要素
1. **Situation**：背景 - 稳定的现状
2. **Complication**：冲突 - 打破现状的变化
3. **Question**：问题 - 核心待解决问题
4. **Answer**：答案 - 你的解决方案/建议

### PPT 结构映射
- 第一部分：背景分析 (S)
- 第二部分：问题诊断 (C)
- 第三部分：解决方案 (Q→A)
- 第四部分：实施路径 (A 的展开)
"""

