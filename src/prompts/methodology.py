# ============================================================
# 麦肯锡金字塔原理 (Pyramid Principle)
# ============================================================
PYRAMID_PRINCIPLE = """
## 金字塔原理 (Pyramid Principle)

核心思想：先说结论，再说论据。

### 结构规则
1. **结论先行**：每一层的观点都是对下一层的总结
2. **以上统下**：上层观点必须是下层观点的抽象概括
3. **归类分组**：同一层的观点必须属于同一逻辑范畴
4. **逻辑递进**：同一层的观点必须按逻辑顺序排列

### MECE 原则
- **Mutually Exclusive**：各部分相互独立，不重叠
- **Collectively Exhaustive**：所有部分完全穷尽，无遗漏

### 应用到 PPT
- 标题 = 结论（不是主题）
- 正文 = 支撑结论的证据
- 每页只讲一个核心观点
"""

# ============================================================
# SCQ 故事线框架 (Situation-Complication-Question)
# ============================================================
SCQ_FRAMEWORK = """
## SCQ 故事线框架

用于构建有说服力的叙事结构。

### 三要素
1. **Situation (情境)**：当前的背景和现状
   - 大家都认同的事实
   - 建立共同的认知基础

2. **Complication (冲突)**：出现的问题或挑战
   - 打破现状的变化
   - 引发紧迫感

3. **Question (问题)**：需要回答的核心问题
   - 自然引出的疑问
   - 引导到解决方案

### 应用示例
- S：我们的市场份额一直稳定在 30%
- C：新竞争者进入，价格战导致份额下滑到 25%
- Q：如何在保持利润的同时夺回市场份额？
"""

# ============================================================
# SCQA 完整框架
# ============================================================
SCQA_FRAMEWORK = """
## SCQA 框架

在 SCQ 基础上增加 Answer，形成完整的说服结构。

### 四要素
1. **Situation**：背景 - 稳定的现状
2. **Complication**：冲突 - 打破现状的变化
3. **Question**：问题 - 核心待解决问题
4. **Answer**：答案 - 你的解决方案/建议

### PPT 结构映射
- 第一部分：背景分析 (S)
- 第二部分：问题诊断 (C)
- 第三部分：解决方案 (Q→A)
- 第四部分：实施路径 (A 的展开)
"""

# ============================================================
# 行动标题原则 (Action Title)
# ============================================================
ACTION_TITLE_PRINCIPLE = """
## 行动标题原则

标题不是主题描述，而是核心结论。

### 错误示例 ❌
- "市场分析"
- "竞争对手情况"
- "财务数据"
- "下一步计划"

### 正确示例 ✅
- "市场规模 5 年内将翻倍，我们必须加速布局"
- "三大竞争对手均在加码研发，我们面临技术落后风险"
- "营收增长 45%，但利润率下滑 3 个百分点需要关注"
- "建议分三阶段推进，首期聚焦核心城市"

### 检验标准
- 读完标题，就知道这页要说什么
- 标题本身就是一个完整的观点
- 标题能独立成为汇报的摘要
"""

# ============================================================
# So What 原则
# ============================================================
SO_WHAT_PRINCIPLE = """
## So What 原则

每一页都要回答：所以呢？这意味着什么？

### 层层追问
1. 数据/事实 → So What?
2. 发现/洞察 → So What?
3. 结论/建议 → 行动

### 应用示例
- 数据：销售额下降 15%
- So What? → 主要是华东区下降，其他区域稳定
- So What? → 华东区新竞品上市抢占了份额
- So What? → 需要针对华东区制定反击策略
- 行动：建议在华东区推出促销活动 + 新品上市

### PPT 应用
- 不要只展示数据，要解读数据
- 不要只描述现象，要分析原因
- 不要只提出问题，要给出建议
"""

# ============================================================
# 一页一观点原则
# ============================================================
ONE_MESSAGE_PER_SLIDE = """
## 一页一观点原则

每页 PPT 只传达一个核心信息。

### 为什么重要
1. 观众注意力有限，信息过多会稀释重点
2. 便于记忆和传播
3. 便于讨论和决策

### 如何判断
- 能否用一句话概括这页的核心信息？
- 这页的所有内容是否都在支撑同一个观点？
- 删掉任何一部分，核心信息是否受影响？

### 常见错误
- 一页塞入多个不相关的数据
- 一页讨论多个话题
- 一页既有问题又有解决方案（应该分开）
"""

# ============================================================
# 数据可视化原则
# ============================================================
DATA_VISUALIZATION_PRINCIPLE = """
## 数据可视化原则

数据不是用来展示的，是用来说服的。

### 选择图表类型
- **比较**：柱状图、条形图
- **趋势**：折线图、面积图
- **占比**：饼图、环形图（不超过 5 个类别）
- **分布**：散点图、直方图
- **关系**：气泡图、热力图

### 数据呈现原则
1. **突出重点**：用颜色、大小突出关键数据
2. **简化信息**：删除不必要的网格线、边框
3. **添加标注**：关键数据点直接标注数值
4. **提供对比**：同比、环比、目标对比

### 数据解读
- 不要让观众自己找结论
- 用文字明确指出数据说明了什么
- 数据要服务于你的论点
"""

